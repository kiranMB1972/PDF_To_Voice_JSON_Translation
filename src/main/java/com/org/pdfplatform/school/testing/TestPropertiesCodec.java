package com.org.pdfplatform.school.testing;

import java.io.IOException;
import java.io.StringReader;
import java.time.LocalDate;
import java.time.format.DateTimeParseException;
import java.util.ArrayList;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Properties;
import java.util.Set;
import java.util.TreeSet;

/**
 * Writes and reads the Test&lt;DD-MM-YYYY&gt;.properties file. The file is the single source of truth for a test:
 * the student's live test screen is built from it (the correct answers stay on the server).
 */
public final class TestPropertiesCodec {

    private TestPropertiesCodec() { }

    public static String write(TestSpec t) {
        StringBuilder sb = new StringBuilder();
        sb.append("# Generated by School Test Portal - configuration of one live test (UTF-8 file; edit it in the Admin > Tests screen)\n");
        line(sb, "test.title", t.title());
        line(sb, "test.date", TestFileNames.DMY.format(t.date()));
        line(sb, "test.class", String.valueOf(t.classLevel()));
        line(sb, "test.subject", t.subject());
        line(sb, "test.duration.minutes", String.valueOf(t.durationMinutes()));
        if (t.materialId() != null) {
            line(sb, "test.material.id", String.valueOf(t.materialId()));
        }
        StringBuilder ids = new StringBuilder();
        for (Long id : t.studentIds()) {
            if (ids.length() > 0) {
                ids.append(',');
            }
            ids.append(id);
        }
        line(sb, "test.students", ids.toString());
        line(sb, "question.count", String.valueOf(t.questions().size()));
        int n = 1;
        for (QuestionSpec q : t.questions()) {
            sb.append('\n');
            line(sb, "question." + n + ".text", q.text());
            for (int i = 0; i < q.options().size(); i++) {
                line(sb, "question." + n + ".option." + QuestionSpec.letter(i), q.options().get(i));
            }
            line(sb, "question." + n + ".correct", String.join(",", new TreeSet<>(q.correct())));
            line(sb, "question." + n + ".marks", String.valueOf(q.marks()));
            n++;
        }
        return sb.toString();
    }

    public static TestSpec read(String text) {
        Properties p = new Properties();
        try {
            p.load(new StringReader(text));
        } catch (IOException e) {
            throw new IllegalArgumentException("The test file could not be read", e);
        }
        LocalDate date;
        try {
            date = LocalDate.parse(req(p, "test.date"), TestFileNames.DMY);
        } catch (DateTimeParseException e) {
            throw new IllegalArgumentException("test.date must look like 29-10-2026");
        }
        int count = Integer.parseInt(req(p, "question.count").trim());
        List<QuestionSpec> qs = new ArrayList<>();
        for (int n = 1; n <= count; n++) {
            List<String> options = new ArrayList<>();
            for (int i = 0; i < 8; i++) {
                String o = p.getProperty("question." + n + ".option." + QuestionSpec.letter(i));
                if (o == null) {
                    break;
                }
                options.add(o);
            }
            Set<String> correct = new LinkedHashSet<>();
            for (String c : req(p, "question." + n + ".correct").split(",")) {
                if (!c.isBlank()) {
                    correct.add(c.trim().toUpperCase());
                }
            }
            int marks = Integer.parseInt(p.getProperty("question." + n + ".marks", "1").trim());
            qs.add(new QuestionSpec(req(p, "question." + n + ".text"), options, correct, marks));
        }
        List<Long> students = new ArrayList<>();
        for (String s : p.getProperty("test.students", "").split(",")) {
            if (!s.isBlank()) {
                students.add(Long.parseLong(s.trim()));
            }
        }
        String mat = p.getProperty("test.material.id");
        return new TestSpec(req(p, "test.title"), Integer.parseInt(req(p, "test.class").trim()), req(p, "test.subject"), date,
                Integer.parseInt(req(p, "test.duration.minutes").trim()),
                mat == null || mat.isBlank() ? null : Long.valueOf(mat.trim()), students, qs);
    }

    private static String req(Properties p, String key) {
        String v = p.getProperty(key);
        if (v == null) {
            throw new IllegalArgumentException("Missing '" + key + "' in the test file");
        }
        return v;
    }

    private static void line(StringBuilder sb, String key, String value) {
        sb.append(key).append('=').append(escape(value == null ? "" : value)).append('\n');
    }

    static String escape(String v) {
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < v.length(); i++) {
            char c = v.charAt(i);
            switch (c) {
                case '\\' -> sb.append("\\\\");
                case '\n' -> sb.append("\\n");
                case '\r' -> sb.append("\\r");
                case '\t' -> sb.append("\\t");
                case ' ' -> sb.append(i == 0 ? "\\ " : " ");
                default -> sb.append(c);
            }
        }
        return sb.toString();
    }
}
